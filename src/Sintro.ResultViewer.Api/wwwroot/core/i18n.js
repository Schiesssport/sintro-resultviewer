export const translate = (dictionary, key, params = {}) => {
    const template = dictionary[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) =>
        Object.hasOwn(params, name) ? String(params[name]) : `{${name}}`);
};
